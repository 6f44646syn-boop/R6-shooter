# Trace the G8A1 from the Abyssal Crown concept into js/scene/g8-model.js (gun space, metres).
#   python3 tools/g8-trace.py docs/legendary-skins/02-abyssal-crown.png
# The whole gun is bronze on a dark backdrop, so the silhouette comes from detail (the backdrop is
# smooth) and colour; parts are cut from it by region so each gets its own thickness.
import json, sys
import numpy as np
from PIL import Image
from trace_lib import grow, components, outline

SRC = sys.argv[1] if len(sys.argv) > 1 else 'docs/legendary-skins/02-abyssal-crown.png'
S = 0.000752                                   # metres per concept pixel (1400 wide): a 1.03 m G8A1
def gun14(x, y): return [round(0.09 + (x - 985) * S, 5), round(-0.03 - (y - 455) * S, 5)]   # grip at the lmg grip, handguard bottom under the hand
to_gun = lambda x, y: gun14(2 * x, 2 * y)

a = np.asarray(Image.open(SRC).convert('RGB').resize((700, 466), Image.LANCZOS)).astype(np.float32)
lum = a.mean(2); H, W = lum.shape
def box(m, r):
    c = np.cumsum(np.cumsum(np.pad(m, ((r + 1, r), (r + 1, r)), mode='edge'), 0), 1)
    return (c[2*r+1:, 2*r+1:] - c[:-2*r-1, 2*r+1:] - c[2*r+1:, :-2*r-1] + c[:-2*r-1, :-2*r-1]) / (2 * r + 1) ** 2
mean = box(lum, 2); std = np.sqrt(np.maximum(box(lum * lum, 2) - mean * mean, 0))
gun = (std > 2.2) | (np.abs(lum - 33) > 14) | (a.max(2) - a.min(2) > 9)
gun = grow(grow(gun, 3, 'or'), 3, 'and'); gun = grow(grow(gun, 1, 'and'), 1, 'or')
yy, xx = np.mgrid[0:H, 0:W]
gun &= (yy < 318) & ~((yy > 300) & ~(((xx > 322) & (xx < 398)) | ((xx > 455) & (xx < 530))))     # floor shadow
lab, sizes = components(gun); gun = lab == max(sizes, key=sizes.get)

# regions (700-wide pixels): [name, depth (m), colour, paint (wears an art skin), region]
REGIONS = [
  ('barrel', 0.024, 'steel', True, (xx < 100) & (yy > 180)),
  ('front sight', 0.012, 'black', True, (xx >= 82) & (xx < 118) & (yy <= 180)),
  ('rear sight', 0.02, 'black', True, (xx >= 462) & (xx < 518) & (yy < 172)),
  ('rail', 0.024, 'black', True, (xx >= 330) & (xx < 462) & (yy < 175)),
  ('grip', 0.032, 'black', True, (xx >= 455) & (xx < 532) & (yy > 236)),
  ('trigger guard', 0.02, 'black', True, (xx >= 398) & (xx < 455) & (yy > 236)),
]
MAG = (xx >= 322) & (xx < 398) & (yy > 228)
taken = np.zeros_like(gun)
parts = []
for name, d, col, paint, region in REGIONS:
    lab, sizes = components(gun & region)
    for k, n in sizes.items():
        if n < 20: continue
        r = lab == k; taken |= r
        hl, hs = components(~r); edge = set(hl[0, :]) | set(hl[-1, :]) | set(hl[:, 0]) | set(hl[:, -1])
        holes = [outline(hl == h, to_gun) for h, hn in hs.items() if h not in edge and hn > 15]
        parts.append({ 'name': name, 'depth': d, 'color': col, 'paint': paint, 'outer': outline(r, to_gun), 'holes': holes })
mag = gun & MAG; taken |= mag
lab, sizes = components(mag); mag = lab == max(sizes, key=sizes.get)
body = gun & ~taken
lab, sizes = components(body); body = lab == max(sizes, key=sizes.get)
# the nautilus medallions (handguard, stock) as rings of rib segments: they open in sequence in the inspect
relief = []
for cx, cy, r in ((627, 405, 48), (1300, 440, 52)):
    for i in range(10):
        a0, a1 = i * 2 * np.pi / 10, (i + 1) * 2 * np.pi / 10 - 0.05
        arc = lambda rad: [(cx + rad * np.cos(t), cy + rad * np.sin(t)) for t in np.linspace(a0, a1, 5)]
        ring = arc(r) + arc(r * 0.38)[::-1]
        relief.append({ 'kind': 'rib', 'area': 0, 'outer': [gun14(x, y) for x, y in ring], 'centre': gun14(cx, cy) })
out = {
  'body': { 'depth': 0.055, 'outer': outline(body, to_gun), 'holes': [] },
  'parts': parts,
  'mag': { 'name': 'magazine', 'depth': 0.062, 'color': 'black', 'paint': True, 'outer': outline(mag, to_gun), 'holes': [] },
  'relief': relief,
  'art': [gun14(0, 0)[0], gun14(1400, 0)[0], gun14(0, 933)[1], gun14(0, 0)[1]],
}
open('js/scene/g8-model.js', 'w').write(
  '// The G8A1, traced from the Abyssal Crown concept (docs/legendary-skins/02-abyssal-crown.png) at real size.\n'
  '// Gun space, metres: [z, y] outlines extruded across x. Generated by tools/g8-trace.py.\n'
  'export const G8 = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print('body', len(out['body']['outer']), 'parts', [(p['name'], len(p['outer'])) for p in parts], 'mag', len(out['mag']['outer']), 'art', out['art'])
