# Trace the F2 from the Storm Kiln concept into js/scene/f2-model.js (gun space, metres).
#   python3 -I tools/f2-trace.py docs/legendary-skins/01-storm-kiln.png
# The concept is a side view (muzzle left). Body: the painted shell (ivory / cobalt), with its window.
# Relief: the raised waves on the stock and the cloud scrolls on the handguard, traced from the
# painting so the 3D matches it. Black parts are drawn from the concept by hand (1400-wide pixels).
import json, sys
import numpy as np
from PIL import Image

SRC = sys.argv[1] if len(sys.argv) > 1 else 'docs/legendary-skins/01-storm-kiln.png'
S = 0.000569                                   # metres per concept pixel (1400 wide): a 757 mm F2
def gun14(x, y): return [round(-0.12 + (x - 760) * S, 5), round(-0.03 - (y - 510) * S, 5)]   # grip at the bullpup grip

im = Image.open(SRC).convert('RGB').resize((700, 466), Image.LANCZOS)
a = np.asarray(im).astype(np.float32)
H, W = a.shape[:2]
lum = a.mean(2)
paint = (lum > 62) | ((a[:, :, 2] > a[:, :, 0] + 18) & (lum > 30))

from trace_lib import grow, components, trace, simplify, outline as _outline
def outline(m, eps=0.8): return _outline(m, lambda x, y: gun14(2 * x, 2 * y), eps)

# body: the painted shell, minus what belongs to the black parts
yy, xx = np.mgrid[0:H, 0:W]
body = grow(grow(paint, 2, 'or'), 2, 'and')
body = grow(grow(body, 1, 'and'), 1, 'or')
body &= ~((xx < 112) | ((xx < 455) & (yy > 257)) | ((xx >= 448) & (xx < 520) & (yy > 292)) | (yy < 116))
lab, sizes = components(body); body = lab == max(sizes, key=sizes.get)
hl, hs = components(~body)
outside = set(hl[0, :]) | set(hl[-1, :]) | set(hl[:, 0]) | set(hl[:, -1])
window = max((k for k in hs if k not in outside), key=hs.get)
for k in hs:
    if k not in outside and k != window: body |= hl == k

# relief: deep cobalt wave bodies on the stock; light glaze of the scroll row on the handguard
blue = (a[:, :, 2] > a[:, :, 0] + 40) & (lum < 150)
waves = blue & (xx > 478) & (xx < 668) & (yy > 172) & (yy < 314) & body
relief = []
for kind, m, minimum in (('wave', grow(grow(waves, 1, 'or'), 1, 'and'), 60),):
    lab, sizes = components(m)
    for k, n in sizes.items():
        if n < minimum: continue
        r = lab == k; ys, xs = np.where(r)
        relief.append({ 'kind': kind, 'area': n, 'outer': outline(r, 0.6), 'centre': gun14(2 * xs.mean(), 2 * ys.mean()) })

def poly(p): return [gun14(x, y) for x, y in p]
# the cloud-scroll band on the handguard (same colour as the glaze around it, so drawn by hand), in four pieces
BAND = [(232, 388, 430), (346, 384, 434), (460, 394, 444), (575, 408, 458), (690, 428, 472)]
for i in range(4):
    (x0, t0, b0), (x1, t1, b1) = BAND[i], BAND[i + 1]
    relief.append({ 'kind': 'scroll', 'area': 0, 'outer': poly([(x0, t0), (x1, t1), (x1, b1), (x0, b0)]), 'centre': gun14((x0 + x1) / 2, (t0 + b0 + t1 + b1) / 4) })
PARTS = [
  ('brake', 0.024, 'steel', [(30,410),(115,410),(115,445),(30,445)], []),
  ('barrel', 0.018, 'black', [(110,416),(240,416),(240,438),(110,438)], []),
  ('rail', 0.026, 'black', [(268,228),(908,228),(908,250),(268,250)], []),
  ('front sight', 0.012, 'black', [(292,236),(300,190),(322,174),(342,190),(348,236)], []),
  ('rear sight', 0.012, 'black', [(822,236),(828,190),(850,174),(872,190),(880,236)], []),
  ('charging handle', 0.03, 'steel', [(300,356),(470,356),(470,378),(300,378)], []),
  ('trigger guard', 0.018, 'black', [(480,500),(648,500),(648,520),(624,590),(500,590),(482,560)], [[(500,518),(626,518),(608,572),(512,572),(498,552)]]),
  ('trigger', 0.008, 'steel', [(560,505),(580,505),(586,545),(568,560),(560,540)], []),
  ('grip', 0.034, 'black', [(652,496),(800,496),(822,560),(828,690),(800,726),(738,726),(722,690),(704,560)], []),
  ('buttpad', 0.05, 'black', [(1326,330),(1352,330),(1364,360),(1364,600),(1352,622),(1326,622)], []),
]
out = {
  'body': { 'depth': 0.05, 'outer': outline(body), 'holes': [outline(hl == window)] },
  'parts': [{ 'name': n, 'depth': d, 'color': c, 'outer': poly(p), 'holes': [poly(h) for h in hs_] } for n, d, c, p, hs_ in PARTS],
  'mag': { 'name': 'magazine', 'depth': 0.03, 'color': 'black', 'outer': poly([(916,560),(1012,560),(1030,640),(1028,712),(1010,756),(928,752),(920,700)]), 'holes': [] },
  'relief': relief,
  'art': gun14(0, 933)[:1] + gun14(1400, 0)[:1] + [gun14(0, 933)[1], gun14(0, 0)[1]],   # the concept's edges: z from, to; y from, to
}
open('js/scene/f2-model.js', 'w').write(
  '// The F2, traced from the Storm Kiln concept (docs/legendary-skins/01-storm-kiln.png) at real size.\n'
  '// Gun space, metres: [z, y] outlines extruded across x. Generated by tools/f2-trace.py.\n'
  'export const F2 = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print('body', len(out['body']['outer']), 'relief', [(r['kind'], r['area']) for r in relief], 'art', out['art'])
